// Builds src/core/palettes/dmc.ts from the DMC floss table.
//
// Source data: https://github.com/sharlagelfand/dmc (MIT, © 2020 Sharla Gelfand),
// file data-raw/floss_adrianj.csv. The fixes below replicate that package's
// data-raw/floss.R cleaning script (mangled hex codes, RGB/hex mismatches, names).
//
// Usage: node scripts/build-dmc.mjs path/to/floss_adrianj.csv

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/build-dmc.mjs <floss_adrianj.csv>');
  process.exit(1);
}

const lines = readFileSync(input, 'utf8').trim().split(/\r?\n/);
const header = lines.shift().split(',');
if (header[0] !== 'Floss#' || header[5] !== 'RGB code') {
  throw new Error(`Unexpected CSV header: ${header.join(',')}`);
}

// Hex codes mangled by Excel in the original sheet.
const MANGLED_HEX = {
  221: '883E43',
  910: '187E56',
  699: '056517',
  869: '835E39',
  310: '000000',
  434: '985E33',
};

// Entries whose RGB and hex columns disagree; values chosen by the dmc package author.
const RGB_HEX_FIX = {
  309: 'BA4A4A',
  3609: 'F4AED5',
  225: 'FFDFD5',
  210: 'C39FC3',
  3755: '93B4CE',
  3849: '52B3AE',
  3848: '419392',
  890: '174923',
  3830: 'B95544',
};

const NAME_FIX = {
  666: 'Red - Bright',
  3846: 'Turquoise - Light Bright',
  3845: 'Turquoise - Medium Bright',
  3844: 'Turquoise - Dark Bright',
  311: 'Navy Blue - Medium',
  943: 'Aquamarine - Medium',
  890: 'Pistachio Green - Ultra Dark',
  934: 'Avocado Green - Black',
  966: 'Baby Green - Medium',
  561: 'Jade - Very Dark',
  608: 'Orange - Bright',
  407: 'Desert Sand - Dark',
  3773: 'Desert Sand - Medium',
};

const ABBREVIATIONS = [
  ['Ult', 'Ultra'],
  ['Vy', 'Very'],
  ['Dk', 'Dark'],
  ['Med', 'Medium'],
  ['Lt', 'Light'],
  ['Vry', 'Very'],
  ['Md', 'Medium'],
  ['M', 'Medium'],
  ['V', 'Very'],
  ['D', 'Dark'],
  ['VD', 'Very Dark'],
  ['VyDk', 'Very Dark'],
  ['Grn', 'Green'],
  ['Brn', 'Brown'],
  ['U', 'Ultra'],
  ['Blu', 'Blue'], // truncated in the source sheet ("Cornflower Blu")
];

// [detection regex, phrase to prefix with "- "]
const DESCRIPTORS = [
  [/Ultra Very Light/, 'Ultra Very Light'],
  [/Ultra Very Dark/, 'Ultra Very Dark'],
  [/Medium Very Light/, 'Medium Very Light'],
  [/Medium Very Dark/, 'Medium Very Dark'],
  [/Medium Light/, 'Medium Light'],
  [/Medium Dark/, 'Medium Dark'],
  [/Ultra Light/, 'Ultra Light'],
  [/Ultra Pale/, 'Ultra Pale'],
  [/Ultra Dark/, 'Ultra Dark'],
  [/Very Light/, 'Very Light'],
  [/Very Dark/, 'Very Dark'],
  [/Pale Light$/, 'Pale Light'],
  [/Light$/, 'Light'],
  [/Pale$/, 'Pale'],
  [/Medium$/, 'Medium'],
  [/Dark$/, 'Dark'],
  [/Bright$/, 'Bright'],
  [/Deep$/, 'Deep'],
];

const squish = (s) => s.replace(/\s+/g, ' ').trim();

function cleanName(raw) {
  let name = squish(raw);
  for (const [abbr, full] of ABBREVIATIONS) {
    name = name.replace(new RegExp(`\\b${abbr}\\b`, 'g'), full);
  }
  name = name.replace(/\?/g, ' ');
  for (const [detect, phrase] of DESCRIPTORS) {
    if (detect.test(name)) {
      name = name.replace(phrase, `- ${phrase}`);
      break;
    }
  }
  name = squish(name).replace('Blue Gray', 'Gray Blue').replace(/Sea Green/g, 'Seagreen');
  return name;
}

const toHex = (r, g, b) =>
  [r, g, b].map((v) => Number(v).toString(16).padStart(2, '0').toUpperCase()).join('');

const out = [];
const seen = new Set();
for (const line of lines) {
  const [code, description, red, green, blue, rgbCode] = line.split(',');
  if (seen.has(code)) throw new Error(`Duplicate DMC code ${code}`);
  seen.add(code);

  let hex = MANGLED_HEX[code] ?? rgbCode.toUpperCase();
  if (!/^[0-9A-F]{6}$/.test(hex)) throw new Error(`Bad hex for ${code}: ${rgbCode}`);
  if (toHex(red, green, blue) !== hex) {
    if (RGB_HEX_FIX[code]) hex = RGB_HEX_FIX[code];
    else console.warn(`RGB/hex mismatch for ${code}, keeping hex ${hex}`);
  }
  const name = NAME_FIX[code] ?? cleanName(description);
  out.push([code, name, hex]);
}

const target = fileURLToPath(new URL('../src/core/palettes/dmc.ts', import.meta.url));
const body = out.map(([c, n, h]) => `  ['${c}', ${JSON.stringify(n)}, '${h}'],`).join('\n');
writeFileSync(
  target,
  `// Generated by scripts/build-dmc.mjs — do not edit by hand.
// DMC floss colours: data from https://github.com/sharlagelfand/dmc (MIT, © 2020 Sharla Gelfand).
// RGB values are screen approximations of real threads. DMC is a trademark of
// Dollfus-Mieg et Compagnie; this project is not affiliated with DMC.

/** [code, English name, hex RGB] in colour-card order. */
export const DMC_RAW: ReadonlyArray<readonly [string, string, string]> = [
${body}
];
`,
);
console.log(`Wrote ${out.length} colours to ${target}`);
